"""gen_traj_chunk.py -- training data for the (e_plunge, T) -> (e0, p0) emulator, from FORWARD FEW integrations.

Why forward: the old backward integration (EMRIInspiral(integrate_backwards=True)) does nothing in the available FEW
(it returns p0 = separatrix, e0 = e_plunge), so e0/p0 are generated by integrating forward from a random (p0, e0) and
recording where the inspiral ends (plunge). A row is kept if the time to plunge is in [T_MIN, T_MAX] yr, which is the
range of the population's T_SIGNAL (the signal duration before plunge).
Row = (lgM, a, Y0, e_plunge, T_to_plunge) -> (e0, p0).
"""
import argparse, os, signal, time
import numpy as np
from few.trajectory.inspiral import EMRIInspiral
from few.utils.utility import get_separatrix

ap = argparse.ArgumentParser()
ap.add_argument("--chunk", type=int, required=True)
ap.add_argument("--n_keep", type=int, default=2000, help="accepted trajectories per chunk")
ap.add_argument("--max_tries", type=int, default=100000)
ap.add_argument("--out_dir", required=True)
ap.add_argument("--master_seed", type=int, default=7)
ap.add_argument("--t_min", type=float, default=0.9); ap.add_argument("--t_max", type=float, default=6.2)
ap.add_argument("--dt", type=float, default=10.0)
ap.add_argument("--per_traj_s", type=int, default=10, help="abort any single trajectory slower than this (s)")
ap.add_argument("--max_wall_s", type=int, default=5400, help="stop the chunk after this wall time and save what was collected")
a = ap.parse_args()
YR = 3.15576e7
os.makedirs(a.out_dir, exist_ok=True)
fn = f"{a.out_dir}/chunk_{a.chunk:04d}.npz"
if os.path.exists(fn): print("exists, skipping", fn); raise SystemExit
rng = np.random.default_rng([a.master_seed, a.chunk])
traj = EMRIInspiral(func="pn5")
class _Slow(Exception): pass
def _alarm(*_): raise _Slow()
signal.signal(signal.SIGALRM, _alarm)
rows = []; tries = 0; fails = 0; slow = 0; t0 = time.time()
while len(rows) < a.n_keep and tries < a.max_tries and time.time() - t0 < a.max_wall_s:
    tries += 1
    lgM = rng.uniform(3.9, 7.1); spin = rng.uniform(0.0, 0.99); Y0 = rng.uniform(0.05, 0.75); e0 = rng.uniform(0.0, 0.95)
    p0 = get_separatrix(spin, e0, Y0) + 10 ** rng.uniform(np.log10(0.3), np.log10(40.0))
    signal.alarm(a.per_traj_s)
    try:
        t, p, e, *_ = traj(10 ** lgM, 10.0, spin, p0, e0, Y0, Phi_phi0=0., Phi_theta0=0., Phi_r0=0., dt=a.dt, T=a.t_max + 1.0)
    except _Slow:
        slow += 1; continue
    except Exception:
        fails += 1; continue
    finally:
        signal.alarm(0)
    dur = t[-1] / YR
    if a.t_min <= dur <= a.t_max:
        rows.append((lgM, spin, Y0, e[-1], dur, e0, p0, p[-1]))
    if tries % 500 == 0: print(f"  tries {tries} kept {len(rows)} slow {slow} fails {fails} {time.time()-t0:.0f}s", flush=True)
r = np.array(rows, dtype=np.float64)
np.savez(fn, lgM=r[:, 0], a=r[:, 1], Y0=r[:, 2], e_plunge=r[:, 3], T=r[:, 4], e0=r[:, 5], p0=r[:, 6], p_plunge=r[:, 7],
         tries=tries, fails=fails, slow=slow)
print(f"chunk {a.chunk}: kept {len(r)} / {tries} tries ({fails} integrator failures, {slow} too slow) in {time.time()-t0:.0f}s")
