#!/bin/sh

. EXECUTABLES/config.sh

MIN_DETECTIONS=2

# SURVEY can be from ZTF LSST
SURVEY=$1


if [ "$SURVEY" = "LSST" ]; then
    Z_MIN=$Z_GAL_MIN_LSST
    Z_MAX=$Z_GAL_MAX_LSST
else
    Z_MIN=$Z_GAL_MIN_ZTF
    Z_MAX=$Z_GAL_MAX_ZTF
fi


OBSERVING_WINDOW_VAR="OBSERVING_WINDOW_TDE_${SURVEY}"
OBSERVING_WINDOW=$(eval echo \$$OBSERVING_WINDOW_VAR)
  
BANDS_VAR="BANDS_${SURVEY}"
BANDS=$(eval echo \$$BANDS_VAR)

python ../calculate_SNR_TDE.py --events $EVENTS --OBSERVING_WINDOW $OBSERVING_WINDOW --MIN_DETECTIONS $MIN_DETECTIONS --SURVEY "$SURVEY" --BANDS $BANDS --Z_MIN $Z_MIN --Z_MAX $Z_MAX